"""Cost-assumption sensitivity: re-evaluate every policy on the TEST split under varied cost parameters.

One parameter of `costs` is changed at a time (grid in config `sensitivity`). RL agents are the
validation-selected checkpoints trained under the BASE costs; they are not retrained per setting.

Outputs: results/metrics/cost_sensitivity.csv, results/figures/cost_sensitivity.png,
         results/reports/cost_sensitivity_report.md
Usage:  python scripts/run_sensitivity.py [--scenarios K]
"""

import _bootstrap  # noqa: F401

import argparse
import time

import pandas as pd

from inventory_rl.agents.ppo import load_policy
from inventory_rl.baselines.rules import RuleBasedPolicy, no_transfer
from inventory_rl.environment.factory import load_context
from inventory_rl.evaluation.report import md_table
from inventory_rl.evaluation.sensitivity import run_setting, settings, sim_config_for, summarize_setting
from inventory_rl.utils.config import load_config
from inventory_rl.utils.paths import FIGURES_DIR, METRICS_DIR, MODELS_DIR, REPORTS_DIR, ensure_dirs
from inventory_rl.visualization import plots

RL_VARIANTS = {"rl_point": ("RL (point forecast)", False), "rl_uncertainty": ("RL (forecast + uncertainty)", True)}
ORDER = ["Rule-based (point)", "Rule-based (upper bound)", "Rule-based (CQR bound)",
         "RL (point forecast)", "RL (forecast + uncertainty)"]


def build_policies(cfg: dict) -> tuple[list, list]:
    pols = [("No redistribution", -1, no_transfer), ("Rule-based (point)", -1, RuleBasedPolicy("point")),
            ("Rule-based (upper bound)", -1, RuleBasedPolicy("upper")),
            ("Rule-based (CQR bound)", -1, RuleBasedPolicy("cqr"))]
    missing = []
    for key, (label, use_unc) in RL_VARIANTS.items():
        for seed in cfg["rl"]["seeds"]:
            path = MODELS_DIR / "rl" / f"{key}_seed{seed}" / "best_model.zip"
            if path.exists():
                pols.append((label, seed, load_policy(path, use_unc, cfg["environment"], label)))
            else:
                missing.append(str(path))
    return pols, missing


def _cell(r) -> str:
    s = f"{r.saving_mean:,.0f}"
    if pd.notna(r.saving_std_train_seeds):
        s += f" ± {r.saving_std_train_seeds:,.0f}"
    return s


def write_report(res: pd.DataFrame, cfg: dict, n_scen: int, missing: list) -> None:
    base = cfg["costs"]
    seeds = cfg["rl"]["seeds"]
    lines = ["# Cost sensitivity report (generated)", "",
             "Generated by `scripts/run_sensitivity.py` on the held-out **test** weeks. One cost parameter is",
             "changed at a time; all others stay at the base values in `config/config.yaml`. Values are the",
             f"modeled saving versus no redistribution, summed over SKUs and weeks, averaged over {n_scen} Poisson",
             "demand scenarios. **RL cells are mean ± std across training seeds** "
             f"(seeds {seeds}; each seed's value is its mean over scenarios). Rule-based policies are deterministic",
             "given the scenarios, so they have no training-seed spread.", "",
             "RL agents were trained under the base costs and are **not retrained** for each setting, and their",
             "actions do not depend on the cost parameters. The rule-based policies adapt to transfer costs",
             "through their cost-per-unit cap. Distances are simulated; cost parameters are assumptions.",
             "'Highest mean saving' compares means only (no significance test); when every policy has a",
             "negative mean saving, not redistributing is cheapest.", ""]
    for scen in ("poisson", "replay"):
        lines += [f"## {scen.capitalize()} demand", ""]
        for param in cfg["sensitivity"]:
            sub = res[(res.scenario == scen) & ((res.parameter == param) | (res.parameter == "base"))].copy()
            sub["value"] = sub.value.fillna(float(base[param]))
            rows = []
            for v, d in sub.sort_values("value").groupby("value", sort=True):
                d = d.set_index("policy")
                row = {param: f"{v:g}" + (" (base)" if v == float(base[param]) else "")}
                for p in ORDER:
                    if p in d.index:
                        row[p] = _cell(d.loc[p])
                means = d.loc[[p for p in ORDER if p in d.index], "saving_mean"]
                # no redistribution has saving 0 by definition
                row["highest mean saving"] = means.idxmax() if means.max() > 0 else "No redistribution"
                rows.append(row)
            lines += [f"### {param}", "", md_table(pd.DataFrame(rows)), ""]
    if missing:
        lines += ["**Warning:** missing RL checkpoints: " + ", ".join(missing), ""]
    (REPORTS_DIR / "cost_sensitivity_report.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--scenarios", type=int, help="Poisson scenarios per setting (default: config)")
    ap.add_argument("--report-only", action="store_true", help="rebuild figure/report from the saved CSV")
    args = ap.parse_args()
    ensure_dirs()
    cfg = load_config()
    n_scen = args.scenarios or cfg["environment"]["eval_poisson_scenarios"]
    if args.report_only:
        res = pd.read_csv(METRICS_DIR / "cost_sensitivity.csv")
        plots.sensitivity_panels(res[res.scenario == "poisson"], cfg["costs"], ORDER,
                                 FIGURES_DIR / "cost_sensitivity.png")
        write_report(res, cfg, n_scen, [])
        return
    ctx = load_context(cfg)
    policies, missing = build_policies(cfg)
    if missing:
        print("WARNING: missing RL checkpoints:", missing)
    rows = []
    for st in settings(cfg):
        t0 = time.time()
        ep = run_setting(ctx, sim_config_for(ctx.sim_cfg, st["parameter"], st["value"]), policies, n_scen)
        rows.append(summarize_setting(ep).assign(**st))
        print(f"{st['parameter']}={st['value']} done in {time.time() - t0:.0f}s", flush=True)
    res = pd.concat(rows, ignore_index=True)
    res = res[res.policy != "No redistribution"]  # saving is 0 by definition
    res.to_csv(METRICS_DIR / "cost_sensitivity.csv", index=False)
    plots.sensitivity_panels(res[res.scenario == "poisson"], cfg["costs"], ORDER,
                             FIGURES_DIR / "cost_sensitivity.png")
    write_report(res, cfg, n_scen, missing)
    print((REPORTS_DIR / "cost_sensitivity_report.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
